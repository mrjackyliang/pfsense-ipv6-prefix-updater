$catalog = static function (array $translations) use ($english): array {
    if (count($translations) !== count($english)) {
        throw new RuntimeException(sprintf(
            'Translation catalog contains %d values; expected %d.',
            count($translations),
            count($english),
        ));
    }

    return array_combine(array_keys($english), $translations);
};

