foreach ($baseCatalogs as $locale => $messages) {
    $baselineRecovery = $baselineRecoveryByLocale[$locale];
    $runtimeErrors = $runtimeErrorsByLocale[$locale];
    $updatedMessagePlurals = $updatedMessagePluralsByLocale[$locale];
    $migration = $migrationByLocale[$locale] ?? [];
    $fieldMessages = $fieldMessagesByLocale[$locale] ?? [];

    if (array_keys($migration) !== array_keys($migrationByLocale['en_US'])) {
        throw new RuntimeException(sprintf('Migration translations for locale "%s" are incomplete.', $locale));
    }

    if (array_keys($fieldMessages) !== array_keys($fieldMessagesByLocale['en_US'])) {
        throw new RuntimeException(sprintf('Field translations for locale "%s" are incomplete.', $locale));
    }

    if (array_keys($baselineRecovery) !== array_keys($baselineRecoveryEnglish)) {
        throw new RuntimeException(sprintf('Baseline-recovery translations for locale "%s" are incomplete.', $locale));
    }

    if (array_keys($runtimeErrors) !== array_keys($runtimeErrorsEnglish)) {
        throw new RuntimeException(sprintf('Runtime-error translations for locale "%s" are incomplete.', $locale));
    }

    if (array_keys($updatedMessagePlurals) !== array_keys($updatedMessagePluralsByLocale['en_US'])) {
        throw new RuntimeException(sprintf('Updated-message plural translations for locale "%s" are incomplete.', $locale));
    }

    $mergedMessages = array_merge(
        $messages,
        $baselineRecovery,
        $updatedMessagePlurals,
        $runtimeErrors,
        $migration,
    );

    if (count(array_intersect_key($fieldMessages, $mergedMessages)) > 0) {
        throw new RuntimeException(sprintf('Field translations for locale "%s" reuse an existing key.', $locale));
    }

    $baseCatalogs[$locale] = array_merge($mergedMessages, $fieldMessages);
}

return $baseCatalogs;
